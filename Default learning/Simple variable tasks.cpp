#include <iostream>
using namespace std;

int main(){
        // ---------------- Student Data Example ----------------
    // Create variables to store student information
    int studentID = 15;          // Student's ID number
    int studentAge = 23;         // Student's age
    double studentFee = 75.25;   // Student's fee (decimal value)
    char studentGrade = 'B';     // Student's grade (single character)

    // Print student information
    cout << "Student ID: " << studentID << "\n";
    cout << "Student Age: " << studentAge << "\n";
    cout << "Student Fee: " << studentFee << "\n";
    cout << "Student Grade: " << studentGrade << "\n";

    return 0;
}