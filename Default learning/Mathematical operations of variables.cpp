#include <iostream>
using namespace std;

int main() {
    // ---------------- Rectangle Example ----------------
    // Create integer variables for length and width
    int length = 4;
    int width = 6;

    // Calculate the area of a rectangle (length × width)
    int area = length * width;

    // Print the variables with messages
    cout << "Length is: " << length << "\n";
    cout << "Width is: " << width << "\n";
    cout << "Area of the rectangle is: " << area << "\n\n";

    return 0;
}
